@router.post("/candidate/cv/generate")
def generate_cv(payload: CvGenerateRequest, current_user: dict = Depends(auth.get_current_user)):
    profile = ProfileIn(**payload.model_dump(exclude={"language"}))

    with get_connection() as conn:
        upsert_profile_fields(conn, current_user["id"], profile)
        row = get_candidate_row(conn, current_user["id"])
        summary = build_profile_summary(row)

        system_prompt = CV_SYSTEM_PROMPT if payload.language == "fr" else CV_SYSTEM_PROMPT_EN
        user_prompt = f"Voici les informations du candidat :\n\n{summary}\n\nRédige le CV."
        cv_text = generate_with_ai(system_prompt, user_prompt, max_tokens=1600)

        conn.execute(
            """
            UPDATE candidates SET
                cv_source = 'generated', cv_filename = NULL, cv_mime = NULL, cv_blob = NULL,
                cv_generated_text = ?, updated_at = ?
            WHERE user_id = ?
            """,
            (cv_text, now_iso(), current_user["id"]),
        )
        row = get_candidate_row(conn, current_user["id"])
        return candidate_to_public_dict(row)


