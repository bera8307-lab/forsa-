class ChatMessageIn(BaseModel):
    role: str = Field(..., pattern="^(user|assistant)$")
    content: str = Field(..., min_length=1, max_length=4000)


class ChatIn(BaseModel):
    messages: List[ChatMessageIn] = Field(..., min_length=1, max_length=20)
    language: str = Field("fr", max_length=5)


CHAT_SYSTEM_PROMPT = (
    "Tu es l'assistant de Forsa, une application qui aide les candidats à trouver des entreprises "
    "et à leur envoyer des candidatures. Tu aides pour : la rédaction et l'amélioration de CV et de "
    "lettres de motivation, les emails de candidature spontanée, la préparation aux entretiens, "
    "les relances et la stratégie de recherche d'emploi (notamment au Maroc et dans l'espace francophone). "
    "Réponds dans la langue du dernier message de l'utilisateur ({language_hint} par défaut). "
    "Sois concret, concis et bienveillant. N'invente aucun fait sur l'utilisateur ou sur une entreprise. "
    "Tu n'as pas accès aux offres d'emploi en temps réel et tu ne peux pas envoyer d'emails toi-même : "
    "l'envoi se fait depuis le bouton « Postuler » de l'application."
)


@router.post("/chat")
def chat(payload: ChatIn, current_user: dict = Depends(auth.get_current_user)):
    """Répond à un message de l'utilisateur en tenant compte de l'historique récent."""
    messages = [{"role": m.role, "content": m.content} for m in payload.messages]
    if messages[-1]["role"] != "user":
        raise HTTPException(status_code=400, detail="Le dernier message doit venir de l'utilisateur.")

    system_prompt = CHAT_SYSTEM_PROMPT.format(
        language_hint="français" if payload.language == "fr" else "English"
    )

    with get_connection() as conn:
        row = get_candidate_row(conn, current_user["id"])
    if row is not None:
        bits = []
        for label, col in (("Nom", "full_name"), ("Poste recherché", "target_role"),
                           ("Compétences", "skills"), ("Langues", "languages")):
            value = (row[col] or "").strip()
            if value:
                bits.append(f"{label} : {value[:300]}")
        if bits:
            system_prompt += "\n\nProfil du candidat (à utiliser seulement si pertinent) :\n" + "\n".join(bits)

    reply = generate_with_ai(
        system_prompt,
        messages[-1]["content"],
        max_tokens=900,
        history=messages[:-1],
    )
    return {"reply": reply}
