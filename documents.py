def init_db() -> None:
    """Crée les tables si besoin (idempotent). Appelé après auth.init_db() (clé étrangère vers users)."""
    with get_connection() as conn:
        conn.execute("SELECT pg_advisory_xact_lock(727402)")
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS candidates (
                user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
                full_name TEXT,
                phone TEXT,
                address TEXT,
                target_role TEXT,
                education TEXT,
                experience TEXT,
                skills TEXT,
                languages TEXT,
                cv_source TEXT NOT NULL DEFAULT 'none',
                cv_filename TEXT,
                cv_mime TEXT,
                cv_blob BYTEA,
                cv_generated_text TEXT,
                updated_at TEXT NOT NULL
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS applications (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                place_id TEXT NOT NULL,
                company_name TEXT,
                company_address TEXT,
                company_category TEXT,
                job_title TEXT,
                cover_letter TEXT,
                status TEXT NOT NULL DEFAULT 'postule',
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL,
                company_email TEXT,
                sent_at TEXT,
                response_status TEXT NOT NULL DEFAULT 'Sent'
                    CHECK (response_status IN ('Sent', 'Replied', 'Interview', 'Rejected')),
                UNIQUE (user_id, place_id)
            )
            """
        )
        # Mise à niveau d'une base créée avec une ancienne version du code.
        # NB : la colonne historique `status` ('postule' / 'envoye') indique brouillon vs envoyée ;
        # le suivi de la réponse de l'entreprise vit dans `response_status`.
        conn.execute("ALTER TABLE applications ADD COLUMN IF NOT EXISTS company_email TEXT")
        conn.execute("ALTER TABLE applications ADD COLUMN IF NOT EXISTS sent_at TEXT")
        conn.execute(
            "ALTER TABLE applications ADD COLUMN IF NOT EXISTS response_status TEXT NOT NULL DEFAULT 'Sent' "
            "CHECK (response_status IN ('Sent', 'Replied', 'Interview', 'Rejected'))"
        )
        conn.execute("CREATE INDEX IF NOT EXISTS idx_applications_user ON applications (user_id)")

        # Voir auth.init_db : Row Level Security activée sans règle = fermé à l'API publique Supabase.
        for table in ("candidates", "applications"):
            conn.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


