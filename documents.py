@router.post("/candidate/cover-letter")
def generate_cover_letter(payload: CoverLetterRequest, current_user: dict = Depends(auth.get_current_user)):
    with get_connection() as conn:
        row = get_candidate_row(conn, current_user["id"])

    if row is None or not (row["full_name"] and (row["experience"] or row["skills"])):
        raise HTTPException(
            status_code=400,
            detail="Complète d'abord ton profil (nom, expérience ou compétences) dans l'espace CV.",
        )

    summary = build_profile_summary(row)
    company_lines = [
        f"Nom de l'entreprise : {payload.company_name}",
        f"Adresse : {payload.company_address or 'non renseignée'}",
        f"Secteur / catégorie : {payload.company_category or 'non renseigné'}",
        f"Poste visé : {payload.job_title or 'poste non précisé, candidature spontanée'}",
    ]
    if payload.notes:
        company_lines.append(f"Notes complémentaires du candidat : {payload.notes}")

    system_prompt = LETTER_SYSTEM_PROMPT if payload.language == "fr" else LETTER_SYSTEM_PROMPT_EN
    user_prompt = (
        f"Profil du candidat :\n{summary}\n\n"
        f"Entreprise ciblée :\n" + "\n".join(company_lines) + "\n\n"
        "Rédige la lettre de motivation."
    )

    letter = generate_with_ai(system_prompt, user_prompt, max_tokens=900)
    return {"cover_letter": letter}


