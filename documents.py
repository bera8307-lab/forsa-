def get_candidate_row(conn: Connection, user_id: int) -> Optional[dict]:
    return conn.execute("SELECT * FROM candidates WHERE user_id = ?", (user_id,)).fetchone()


def candidate_to_public_dict(row: Optional[dict]) -> dict:
    if row is None:
        return {
            "full_name": None,
            "phone": None,
            "address": None,
            "target_role": None,
            "education": None,
            "experience": None,
            "skills": None,
            "languages": None,
            "cv_source": "none",
            "cv_filename": None,
            "cv_generated_text": None,
            "has_cv": False,
            "updated_at": None,
        }
    return {
        "full_name": row["full_name"],
        "phone": row["phone"],
        "address": row["address"],
        "target_role": row["target_role"],
        "education": row["education"],
        "experience": row["experience"],
        "skills": row["skills"],
        "languages": row["languages"],
        "cv_source": row["cv_source"],
        "cv_filename": row["cv_filename"],
        "cv_generated_text": row["cv_generated_text"],
        "has_cv": row["cv_source"] in ("upload", "generated"),
        "updated_at": row["updated_at"],
    }


def upsert_profile_fields(conn: Connection, user_id: int, payload: ProfileIn) -> None:
    existing = get_candidate_row(conn, user_id)
    if existing is None:
        conn.execute(
            """
            INSERT INTO candidates
                (user_id, full_name, phone, address, target_role, education, experience, skills, languages, cv_source, updated_at)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'none', ?)
            """,
            (
                user_id, payload.full_name, payload.phone, payload.address, payload.target_role,
                payload.education, payload.experience, payload.skills, payload.languages, now_iso(),
            ),
        )
    else:
        conn.execute(
            """
            UPDATE candidates SET
                full_name = ?, phone = ?, address = ?, target_role = ?,
                education = ?, experience = ?, skills = ?, languages = ?, updated_at = ?
            WHERE user_id = ?
            """,
            (
                payload.full_name, payload.phone, payload.address, payload.target_role,
                payload.education, payload.experience, payload.skills, payload.languages,
                now_iso(), user_id,
            ),
        )


def build_profile_summary(row: dict) -> str:
    lines = [
        f"Nom complet : {row['full_name'] or 'non renseigné'}",
        f"Poste recherché : {row['target_role'] or 'non renseigné'}",
        f"Téléphone : {row['phone'] or 'non renseigné'}",
        f"Adresse : {row['address'] or 'non renseignée'}",
        f"Formation : {row['education'] or 'non renseignée'}",
        f"Expérience professionnelle : {row['experience'] or 'non renseignée'}",
        f"Compétences : {row['skills'] or 'non renseignées'}",
        f"Langues : {row['languages'] or 'non renseignées'}",
    ]
    return "\n".join(lines)


