def generate_with_ai(
    system_prompt: str,
    user_prompt: str,
    max_tokens: int = 1400,
    history: Optional[List[dict]] = None,
) -> str:
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        raise HTTPException(
            status_code=500,
            detail="Clé API IA manquante côté serveur. Ajoute GROQ_API_KEY dans le fichier .env.",
        )

    model = os.getenv("GROQ_MODEL", "llama-3.3-70b-versatile")
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    }
    body = {
        "model": model,
        "max_tokens": max_tokens,
        "messages": [
            {"role": "system", "content": system_prompt},
            *(history or []),
            {"role": "user", "content": user_prompt},
        ],
    }

    try:
        response = requests.post(GROQ_URL, headers=headers, json=body, timeout=60)
    except requests.RequestException as exc:
        raise HTTPException(status_code=502, detail=f"Impossible de contacter l'IA : {exc}") from exc

    if response.status_code != 200:
        raise HTTPException(
            status_code=502,
            detail=f"Erreur de l'API IA ({response.status_code}) : {response.text[:300]}",
        )

    data = response.json()
    choices = data.get("choices", [])
    text = ""
    if choices:
        text = (choices[0].get("message", {}).get("content") or "").strip()

    if not text:
        raise HTTPException(status_code=502, detail="Réponse vide de l'IA.")

    return text


