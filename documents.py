SIMPLE_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")


class SendApplicationIn(BaseModel):
    place_id: str = Field(..., min_length=1, max_length=300)
    company_name: str = Field(..., min_length=1, max_length=200)
    company_address: Optional[str] = Field(None, max_length=300)
    company_category: Optional[str] = Field(None, max_length=150)
    company_email: str = Field(..., min_length=3, max_length=254)
    job_title: Optional[str] = Field(None, max_length=150)
    subject: Optional[str] = Field(None, max_length=200)
    message: str = Field(..., min_length=1, max_length=8000)


def send_email_smtp(msg: EmailMessage) -> None:
    """Envoie la candidature (API Brevo en ligne, SMTP sur ton PC) : voir mailer.deliver()."""
    try:
        mailer.deliver(msg)
    except mailer.MailError as exc:
        raise HTTPException(status_code=exc.status_code, detail=str(exc)) from exc


@router.post("/applications/send")
def send_application(payload: SendApplicationIn, current_user: dict = Depends(auth.get_current_user)):
    """Envoie la candidature (message + CV en pièce jointe) à l'email de l'entreprise."""
    to_email = payload.company_email.strip()
    if not SIMPLE_EMAIL_RE.match(to_email):
        raise HTTPException(status_code=400, detail="Adresse email de l'entreprise invalide.")

    with get_connection() as conn:
        row = get_candidate_row(conn, current_user["id"])

    if row is None or row["cv_source"] not in ("upload", "generated"):
        raise HTTPException(status_code=400, detail="Ajoute d'abord un CV dans « Mon CV » pour pouvoir l'envoyer.")

    candidate_name = (row["full_name"] or current_user.get("name") or "Candidat").strip()
    user_email = current_user.get("email")
    from_addr = mailer.default_from_address()

    subject = (payload.subject or "").strip() or (
        f"Candidature - {payload.job_title}" if payload.job_title else f"Candidature spontanée - {candidate_name}"
    )

    msg = EmailMessage()
    msg["From"] = f"{candidate_name} <{from_addr}>"
    msg["To"] = to_email
    if user_email:
        msg["Reply-To"] = f"{candidate_name} <{user_email}>"  # les réponses arrivent directement chez le candidat
    msg["Subject"] = subject
    msg.set_content(payload.message)

    if row["cv_source"] == "upload" and row["cv_blob"]:
        filename = row["cv_filename"] or "CV.pdf"
        mime = row["cv_mime"] or mimetypes.guess_type(filename)[0] or "application/octet-stream"
        maintype, _, subtype = mime.partition("/")
        msg.add_attachment(bytes(row["cv_blob"]), maintype=maintype, subtype=subtype or "octet-stream", filename=filename)
    else:
        text = row["cv_generated_text"] or ""
        safe_name = re.sub(r"[^A-Za-z0-9_-]+", "_", candidate_name) or "CV"
        msg.add_attachment(text.encode("utf-8"), maintype="text", subtype="plain", filename=f"CV_{safe_name}.txt")

    send_email_smtp(msg)

    with get_connection() as conn:
        existing = conn.execute(
            "SELECT id FROM applications WHERE user_id = ? AND place_id = ?",
            (current_user["id"], payload.place_id),
        ).fetchone()
        ts = now_iso()
        if existing:
            conn.execute(
                """
                UPDATE applications SET
                    company_name = ?, company_address = ?, company_category = ?, job_title = ?,
                    cover_letter = ?, company_email = ?, sent_at = ?, status = 'envoye', updated_at = ?
                WHERE id = ?
                """,
                (payload.company_name, payload.company_address, payload.company_category, payload.job_title,
                 payload.message, to_email, ts, ts, existing["id"]),
            )
            app_id = existing["id"]
        else:
            cursor = conn.execute(
                """
                INSERT INTO applications
                    (user_id, place_id, company_name, company_address, company_category, job_title,
                     cover_letter, company_email, sent_at, status, created_at, updated_at)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'envoye', ?, ?)
                RETURNING id
                """,
                (current_user["id"], payload.place_id, payload.company_name, payload.company_address,
                 payload.company_category, payload.job_title, payload.message, to_email, ts, ts, ts),
            )
            app_id = cursor.fetchone()["id"]
        saved = conn.execute("SELECT * FROM applications WHERE id = ?", (app_id,)).fetchone()
        return application_to_dict(saved)


