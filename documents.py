@router.patch("/applications/{app_id}/status")
def update_application_status(
    app_id: int,
    payload: ApplicationStatusUpdate,
    current_user: dict = Depends(auth.get_current_user),
):
    with get_connection() as conn:
        row = conn.execute(
            "SELECT * FROM applications WHERE id = ? AND user_id = ?",
            (app_id, current_user["id"]),
        ).fetchone()
        if not row:
            raise HTTPException(status_code=404, detail="Candidature introuvable.")
        if row["status"] != "envoye":
            raise HTTPException(status_code=400, detail="Seules les candidatures envoyées ont un statut de suivi.")
        conn.execute(
            "UPDATE applications SET response_status = ?, updated_at = ? WHERE id = ?",
            (payload.status, now_iso(), app_id),
        )
        updated = conn.execute("SELECT * FROM applications WHERE id = ?", (app_id,)).fetchone()
    return application_to_dict(updated)


