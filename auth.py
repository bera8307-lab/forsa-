"""Authentification simple par email/mot de passe, sans dépendance externe.

Stocke les comptes dans la base Postgres (Supabase, voir db.py) et
les sessions actives dans une seconde table. Les mots de passe ne sont
jamais stockés en clair : on garde un sel aléatoire par utilisateur et un
hash PBKDF2-SHA256.
"""

import csv
import hashlib
import re
import secrets
import threading
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from typing import Optional

from fastapi import APIRouter, Depends, Header, HTTPException
from pydantic import BaseModel, Field, field_validator

import mailer
from db import get_connection

EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")

PHONE_RE = re.compile(r"^\+?[0-9\s().-]{6,25}$")

SIGNUPS_CSV_PATH = Path(__file__).parent / "signups.csv"
CODE_LIFETIME_MINUTES = 15   # durée de validité d'un code
CODE_MAX_ATTEMPTS = 5        # essais maximum avant de devoir redemander un code
CODE_RESEND_SECONDS = 60     # délai minimum entre deux envois de code
CSV_COLUMNS = ["id", "first_name", "last_name", "phone", "email", "birth_date", "created_at"]
_csv_lock = threading.Lock()
SESSION_LIFETIME_DAYS = 30
PBKDF2_ITERATIONS = 200_000

router = APIRouter(prefix="/api/auth", tags=["auth"])


def init_db() -> None:
    """Crée les tables si besoin (idempotent). Le verrou évite qu'un double démarrage ne se télescope."""
    with get_connection() as conn:
        conn.execute("SELECT pg_advisory_xact_lock(727401)")
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                salt TEXT NOT NULL,
                created_at TEXT NOT NULL,
                first_name TEXT,
                last_name TEXT,
                phone TEXT,
                birth_date TEXT,
                email_verified INTEGER NOT NULL DEFAULT 1
            )
            """
        )
        # Mise à niveau d'une base créée avec une ancienne version du code.
        for column in ("first_name", "last_name", "phone", "birth_date"):
            conn.execute(f"ALTER TABLE users ADD COLUMN IF NOT EXISTS {column} TEXT")
        # Les comptes déjà existants sont considérés comme vérifiés (DEFAULT 1) ;
        # les nouvelles inscriptions sont créées avec email_verified = 0.
        conn.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified INTEGER NOT NULL DEFAULT 1")

        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS email_codes (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL,
                purpose TEXT NOT NULL,
                code_hash TEXT NOT NULL,
                attempts INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL,
                expires_at TEXT NOT NULL
            )
            """
        )
        conn.execute("CREATE INDEX IF NOT EXISTS idx_email_codes_lookup ON email_codes (email, purpose)")
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS sessions (
                token TEXT PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                created_at TEXT NOT NULL,
                expires_at TEXT NOT NULL
            )
            """
        )
        conn.execute("CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id)")

        # Supabase expose les tables du schéma « public » via une API publique (clé anon).
        # Row Level Security activée SANS règle = aucun accès par cette API. Notre serveur,
        # lui, se connecte avec le rôle « postgres » qui n'est pas concerné.
        for table in ("users", "email_codes", "sessions"):
            conn.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")


def hash_password(password: str, salt: Optional[str] = None) -> tuple[str, str]:
    salt = salt or secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac(
        "sha256", password.encode("utf-8"), bytes.fromhex(salt), PBKDF2_ITERATIONS
    )
    return digest.hex(), salt


def verify_password(password: str, password_hash: str, salt: str) -> bool:
    candidate, _ = hash_password(password, salt)
    return secrets.compare_digest(candidate, password_hash)


def create_session(user_id: int) -> str:
    token = secrets.token_urlsafe(32)
    now = datetime.now(timezone.utc)
    expires = now + timedelta(days=SESSION_LIFETIME_DAYS)
    with get_connection() as conn:
        conn.execute(
            "INSERT INTO sessions (token, user_id, created_at, expires_at) VALUES (?, ?, ?, ?)",
            (token, user_id, now.isoformat(), expires.isoformat()),
        )
    return token


def user_to_dict(row: dict) -> dict:
    keys = row.keys()
    return {
        "id": row["id"],
        "name": row["name"],
        "email": row["email"],
        "first_name": row["first_name"] if "first_name" in keys else None,
        "last_name": row["last_name"] if "last_name" in keys else None,
        "phone": row["phone"] if "phone" in keys else None,
        "birth_date": row["birth_date"] if "birth_date" in keys else None,
    }


def append_signup_to_csv(record: dict) -> None:
    """Ajoute une ligne dans signups.csv (jamais le mot de passe).

    Le fichier est créé avec son en-tête au premier appel. L'encodage utf-8-sig
    permet à Excel d'afficher correctement les accents.
    """
    with _csv_lock:
        is_new = not SIGNUPS_CSV_PATH.exists() or SIGNUPS_CSV_PATH.stat().st_size == 0
        with open(SIGNUPS_CSV_PATH, "a", newline="", encoding="utf-8-sig") as f:
            writer = csv.DictWriter(f, fieldnames=CSV_COLUMNS)
            if is_new:
                writer.writeheader()
            writer.writerow({col: record.get(col, "") for col in CSV_COLUMNS})


def hash_code(email: str, purpose: str, code: str) -> str:
    return hashlib.sha256(f"{email}:{purpose}:{code}".encode("utf-8")).hexdigest()


def issue_code(email: str, purpose: str) -> Optional[str]:
    """Crée un code à 6 chiffres (stocké haché). Retourne None si le dernier code est trop récent."""
    now = datetime.now(timezone.utc)
    with get_connection() as conn:
        row = conn.execute(
            "SELECT created_at FROM email_codes WHERE email = ? AND purpose = ?", (email, purpose)
        ).fetchone()
        if row and (now - datetime.fromisoformat(row["created_at"])).total_seconds() < CODE_RESEND_SECONDS:
            return None

        code = f"{secrets.randbelow(10**6):06d}"
        conn.execute("DELETE FROM email_codes WHERE email = ? AND purpose = ?", (email, purpose))
        conn.execute(
            "INSERT INTO email_codes (email, purpose, code_hash, attempts, created_at, expires_at) VALUES (?, ?, ?, 0, ?, ?)",
            (
                email,
                purpose,
                hash_code(email, purpose, code),
                now.isoformat(),
                (now + timedelta(minutes=CODE_LIFETIME_MINUTES)).isoformat(),
            ),
        )
    return code


def discard_code(email: str, purpose: str) -> None:
    with get_connection() as conn:
        conn.execute("DELETE FROM email_codes WHERE email = ? AND purpose = ?", (email, purpose))


def check_code(email: str, purpose: str, code: str) -> None:
    """Vérifie un code. Lève une HTTPException 400 s'il est faux, expiré ou épuisé."""
    error: Optional[str] = None
    with get_connection() as conn:
        row = conn.execute(
            "SELECT * FROM email_codes WHERE email = ? AND purpose = ?", (email, purpose)
        ).fetchone()

        if not row:
            error = "Code incorrect ou expiré."
        elif datetime.fromisoformat(row["expires_at"]) < datetime.now(timezone.utc):
            conn.execute("DELETE FROM email_codes WHERE id = ?", (row["id"],))
            error = "Ce code a expiré. Demande-en un nouveau."
        elif row["attempts"] >= CODE_MAX_ATTEMPTS:
            conn.execute("DELETE FROM email_codes WHERE id = ?", (row["id"],))
            error = "Trop de tentatives. Demande un nouveau code."
        elif not secrets.compare_digest(row["code_hash"], hash_code(email, purpose, code.strip())):
            attempts = row["attempts"] + 1
            if attempts >= CODE_MAX_ATTEMPTS:
                conn.execute("DELETE FROM email_codes WHERE id = ?", (row["id"],))
                error = "Trop de tentatives. Demande un nouveau code."
            else:
                conn.execute("UPDATE email_codes SET attempts = ? WHERE id = ?", (attempts, row["id"]))
                error = "Code incorrect."
        else:
            conn.execute("DELETE FROM email_codes WHERE id = ?", (row["id"],))

    # L'exception est levée après le bloc `with` pour que les changements ci-dessus soient bien enregistrés.
    if error:
        raise HTTPException(status_code=400, detail=error)


def send_code_email(email: str, first_name: str, purpose: str, code: str) -> None:
    """Envoie le code par email. Lève mailer.MailError en cas d'échec."""
    if purpose == "verify":
        mailer.send_verification_code(email, first_name, code, CODE_LIFETIME_MINUTES)
    else:
        mailer.send_reset_code(email, first_name, code, CODE_LIFETIME_MINUTES)


def get_current_user(authorization: Optional[str] = Header(None)) -> dict:
    if not authorization or not authorization.startswith("Bearer "):
        raise HTTPException(status_code=401, detail="Authentification requise.")

    token = authorization.removeprefix("Bearer ").strip()

    with get_connection() as conn:
        session_row = conn.execute(
            "SELECT * FROM sessions WHERE token = ?", (token,)
        ).fetchone()

        if not session_row:
            raise HTTPException(status_code=401, detail="Session invalide, reconnecte-toi.")

        expires_at = datetime.fromisoformat(session_row["expires_at"])
        if expires_at < datetime.now(timezone.utc):
            conn.execute("DELETE FROM sessions WHERE token = ?", (token,))
            raise HTTPException(status_code=401, detail="Session expirée, reconnecte-toi.")

        user_row = conn.execute(
            "SELECT * FROM users WHERE id = ?", (session_row["user_id"],)
        ).fetchone()

        if not user_row:
            raise HTTPException(status_code=401, detail="Compte introuvable.")

        return user_to_dict(user_row)


class SignupRequest(BaseModel):
    first_name: str = Field(..., min_length=1, max_length=60)
    last_name: str = Field(..., min_length=1, max_length=60)
    phone: str = Field(..., min_length=6, max_length=25)
    email: str = Field(..., min_length=3, max_length=254)
    birth_date: str = Field(..., description="Date de naissance au format AAAA-MM-JJ")
    password: str = Field(..., min_length=6, max_length=128)

    @field_validator("first_name", "last_name")
    @classmethod
    def validate_names(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("Ce champ est obligatoire.")
        return value

    @field_validator("email")
    @classmethod
    def validate_email(cls, value: str) -> str:
        if not EMAIL_RE.match(value.strip()):
            raise ValueError("Adresse email invalide.")
        return value

    @field_validator("phone")
    @classmethod
    def validate_phone(cls, value: str) -> str:
        value = value.strip()
        digits = re.sub(r"\D", "", value)
        if not PHONE_RE.match(value) or not (6 <= len(digits) <= 15):
            raise ValueError("Numéro de téléphone invalide.")
        return value

    @field_validator("birth_date")
    @classmethod
    def validate_birth_date(cls, value: str) -> str:
        try:
            parsed = date.fromisoformat(value.strip())
        except ValueError:
            raise ValueError("Date de naissance invalide.")
        if parsed > date.today() or parsed.year < 1900:
            raise ValueError("Date de naissance invalide.")
        return parsed.isoformat()


class LoginRequest(BaseModel):
    email: str = Field(..., min_length=3, max_length=254)
    password: str = Field(..., min_length=1, max_length=128)


class EmailOnlyRequest(BaseModel):
    email: str = Field(..., min_length=3, max_length=254)


class VerifyEmailRequest(BaseModel):
    email: str = Field(..., min_length=3, max_length=254)
    code: str = Field(..., min_length=6, max_length=6, pattern=r"^[0-9]{6}$")


class ResetPasswordRequest(BaseModel):
    email: str = Field(..., min_length=3, max_length=254)
    code: str = Field(..., min_length=6, max_length=6, pattern=r"^[0-9]{6}$")
    new_password: str = Field(..., min_length=6, max_length=128)


@router.post("/signup")
def signup(payload: SignupRequest):
    email = payload.email.lower().strip()
    first_name = payload.first_name.strip()
    last_name = payload.last_name.strip()
    phone = payload.phone.strip()
    birth_date = payload.birth_date
    name = f"{first_name} {last_name}"  # "name" reste utilisé par le reste de l'app
    created_at = datetime.now(timezone.utc).isoformat()
    password_hash, salt = hash_password(payload.password)

    with get_connection() as conn:
        existing = conn.execute(
            "SELECT id, email_verified FROM users WHERE email = ?", (email,)
        ).fetchone()
        if existing and existing["email_verified"]:
            raise HTTPException(status_code=400, detail="Un compte existe déjà avec cet email.")

        if existing:
            # Inscription jamais confirmée (ex. faute de frappe) : on la remplace par la nouvelle.
            conn.execute(
                """
                UPDATE users SET name = ?, first_name = ?, last_name = ?, phone = ?, birth_date = ?,
                                 password_hash = ?, salt = ?
                WHERE id = ?
                """,
                (name, first_name, last_name, phone, birth_date, password_hash, salt, existing["id"]),
            )
        else:
            conn.execute(
                """
                INSERT INTO users
                    (name, first_name, last_name, phone, birth_date, email, password_hash, salt, created_at, email_verified)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 0)
                """,
                (name, first_name, last_name, phone, birth_date, email, password_hash, salt, created_at),
            )

    # Le compte n'est actif (et pas de session) qu'après la saisie du code reçu par email.
    code = issue_code(email, "verify")
    if code:
        try:
            send_code_email(email, first_name, "verify", code)
        except mailer.MailError as exc:
            discard_code(email, "verify")
            raise HTTPException(status_code=502, detail=str(exc)) from exc

    return {"verification_required": True, "email": email}


@router.post("/verify-email")
def verify_email(payload: VerifyEmailRequest):
    email = payload.email.lower().strip()

    with get_connection() as conn:
        user_row = conn.execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()

    if not user_row:
        raise HTTPException(status_code=400, detail="Code incorrect ou expiré.")
    if user_row["email_verified"]:
        raise HTTPException(status_code=400, detail="Ce compte est déjà vérifié. Tu peux te connecter.")

    check_code(email, "verify", payload.code)

    with get_connection() as conn:
        conn.execute("UPDATE users SET email_verified = 1 WHERE id = ?", (user_row["id"],))
        user_row = conn.execute("SELECT * FROM users WHERE id = ?", (user_row["id"],)).fetchone()

    # Sauvegarde dans signups.csv (sans le mot de passe), seulement une fois l'email confirmé.
    # Une erreur d'écriture ne doit pas empêcher la connexion : le compte est déjà dans la base.
    try:
        append_signup_to_csv({col: user_row[col] for col in CSV_COLUMNS})
    except OSError as exc:
        print(f"[signup] Impossible d'écrire signups.csv : {exc}")

    token = create_session(user_row["id"])
    return {"token": token, "user": user_to_dict(user_row)}


@router.post("/resend-code")
def resend_code(payload: EmailOnlyRequest):
    """Renvoie le code de vérification. Réponse identique que le compte existe ou non."""
    email = payload.email.lower().strip()

    with get_connection() as conn:
        user_row = conn.execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()

    if user_row and not user_row["email_verified"]:
        code = issue_code(email, "verify")  # None si un code vient d'être envoyé (anti-spam)
        if code:
            try:
                send_code_email(email, user_row["first_name"] or user_row["name"], "verify", code)
            except mailer.MailError as exc:
                discard_code(email, "verify")
                print(f"[auth] Échec d'envoi du code de vérification : {exc}")

    return {"ok": True}


@router.post("/forgot-password")
def forgot_password(payload: EmailOnlyRequest):
    """Envoie un code de réinitialisation. Réponse identique que le compte existe ou non."""
    email = payload.email.lower().strip()

    with get_connection() as conn:
        user_row = conn.execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()

    if user_row:
        code = issue_code(email, "reset")
        if code:
            try:
                send_code_email(email, user_row["first_name"] or user_row["name"], "reset", code)
            except mailer.MailError as exc:
                discard_code(email, "reset")
                print(f"[auth] Échec d'envoi du code de réinitialisation : {exc}")

    return {"ok": True, "message": "Si un compte existe avec cet email, un code vient d'être envoyé."}


@router.post("/reset-password")
def reset_password(payload: ResetPasswordRequest):
    email = payload.email.lower().strip()

    check_code(email, "reset", payload.code)

    password_hash, salt = hash_password(payload.new_password)
    with get_connection() as conn:
        user_row = conn.execute("SELECT id FROM users WHERE email = ?", (email,)).fetchone()
        if not user_row:
            raise HTTPException(status_code=400, detail="Code incorrect ou expiré.")
        # Réussir la réinitialisation prouve aussi que l'email appartient à l'utilisateur.
        conn.execute(
            "UPDATE users SET password_hash = ?, salt = ?, email_verified = 1 WHERE id = ?",
            (password_hash, salt, user_row["id"]),
        )
        # Déconnecte tous les appareils : l'ancien mot de passe ne doit plus donner accès.
        conn.execute("DELETE FROM sessions WHERE user_id = ?", (user_row["id"],))

    return {"ok": True}


@router.post("/login")
def login(payload: LoginRequest):
    email = payload.email.lower().strip()

    with get_connection() as conn:
        user_row = conn.execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()

    if not user_row or not verify_password(payload.password, user_row["password_hash"], user_row["salt"]):
        raise HTTPException(status_code=401, detail="Email ou mot de passe incorrect.")

    if not user_row["email_verified"]:
        # Mot de passe correct mais email jamais confirmé : on renvoie un code (si le dernier est assez ancien).
        code = issue_code(email, "verify")
        if code:
            try:
                send_code_email(email, user_row["first_name"] or user_row["name"], "verify", code)
            except mailer.MailError as exc:
                discard_code(email, "verify")
                print(f"[auth] Échec d'envoi du code de vérification : {exc}")
        raise HTTPException(
            status_code=403,
            detail="Ton email n'est pas encore vérifié. Entre le code que nous t'avons envoyé.",
        )

    token = create_session(user_row["id"])
    return {"token": token, "user": user_to_dict(user_row)}


@router.post("/logout")
def logout(authorization: Optional[str] = Header(None)):
    if authorization and authorization.startswith("Bearer "):
        token = authorization.removeprefix("Bearer ").strip()
        with get_connection() as conn:
            conn.execute("DELETE FROM sessions WHERE token = ?", (token,))
    return {"ok": True}


@router.get("/me")
def me(current_user: dict = Depends(get_current_user)):
    return current_user
