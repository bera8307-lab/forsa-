-- Schéma Forsa pour Supabase (Postgres).
--
-- OPTIONNEL : l'application crée exactement ces tables toute seule au démarrage
-- (auth.init_db / documents.init_db). Ce fichier sert si tu préfères les créer à la main :
-- Supabase > SQL Editor > New query > colle ce fichier > Run. Tu peux l'exécuter plusieurs fois.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    salt TEXT NOT NULL,
    created_at TEXT NOT NULL,
    first_name TEXT,
    last_name TEXT,
    phone TEXT,
    birth_date TEXT,
    email_verified INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS email_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    purpose TEXT NOT NULL,
    code_hash TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_email_codes_lookup ON email_codes (email, purpose);

CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);

CREATE TABLE IF NOT EXISTS candidates (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    full_name TEXT,
    phone TEXT,
    address TEXT,
    target_role TEXT,
    education TEXT,
    experience TEXT,
    skills TEXT,
    languages TEXT,
    cv_source TEXT NOT NULL DEFAULT 'none',
    cv_filename TEXT,
    cv_mime TEXT,
    cv_blob BYTEA,
    cv_generated_text TEXT,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    place_id TEXT NOT NULL,
    company_name TEXT,
    company_address TEXT,
    company_category TEXT,
    job_title TEXT,
    cover_letter TEXT,
    status TEXT NOT NULL DEFAULT 'postule',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    company_email TEXT,
    sent_at TEXT,
    response_status TEXT NOT NULL DEFAULT 'Sent'
        CHECK (response_status IN ('Sent', 'Replied', 'Interview', 'Rejected')),
    UNIQUE (user_id, place_id)
);
CREATE INDEX IF NOT EXISTS idx_applications_user ON applications (user_id);

-- Tickets à usage unique pour la recherche en direct (durée de vie : 60 secondes).
CREATE TABLE IF NOT EXISTS search_tickets (
    ticket TEXT PRIMARY KEY,
    payload TEXT NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL
);

-- SÉCURITÉ ------------------------------------------------------------------
-- Supabase expose automatiquement les tables du schéma « public » via une API
-- publique utilisable avec la clé « anon » (visible dans le navigateur de n'importe qui).
-- Row Level Security activée SANS aucune règle = cette API ne peut rien lire ni écrire.
-- Ton serveur Forsa se connecte directement à Postgres (rôle « postgres ») et n'est
-- pas concerné. Ne crée PAS de règle « using (true) » sur ces tables : elles contiennent
-- les hash de mots de passe et les CV.
ALTER TABLE users        ENABLE ROW LEVEL SECURITY;
ALTER TABLE email_codes  ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions     ENABLE ROW LEVEL SECURITY;
ALTER TABLE candidates   ENABLE ROW LEVEL SECURITY;
ALTER TABLE applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE search_tickets ENABLE ROW LEVEL SECURITY;

-- Double sécurité : retire aussi les droits des rôles de l'API publique.
REVOKE ALL ON users, email_codes, sessions, candidates, applications, search_tickets FROM anon, authenticated;
